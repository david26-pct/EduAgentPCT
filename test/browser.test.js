import { test } from 'node:test';
import assert from 'node:assert/strict';
import { chromium } from '@playwright/test';
import { mkdtempSync, rmSync, mkdirSync, readFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';
import { createApp } from '../server.js';

test('Browser desktop dan mobile: daftar, tambah peserta, pratinjau, simpan, dan unduh PDF', async () => {
  const dir = mkdtempSync(join(tmpdir(), 'eduagent-browser-'));
  const { app, db } = createApp({ databasePath: join(dir, 'browser.sqlite') });
  db.prepare('INSERT INTO partners(name,recipient) VALUES(?,?)').run('Instansi Uji Browser', 'Manager');
  const server = app.listen(0, '127.0.0.1'); await new Promise(r => server.once('listening', r));
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
  const page = await context.newPage(); const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  try {
    await page.goto(`http://127.0.0.1:${server.address().port}`);
    const loginLogo = page.locator('#auth .brand-mark img');
    await loginLogo.waitFor({ state: 'visible' });
    assert.equal(await loginLogo.evaluate(img => img.complete && img.naturalWidth === 1239), true);
    await page.locator('#register-tab').click();
    await page.locator('#auth-form [name=name]').fill('Siswa Browser');
    await page.locator('#auth-form [name=nis]').fill('20260001');
    await page.locator('#auth-form [name=password]').fill('password-browser-aman');
    await page.locator('#auth-form [name=confirm]').fill('password-browser-aman');
    await page.locator('#auth-submit').click();
    await page.locator('#greeting').waitFor();
    assert.equal(await page.locator('aside .brand-mark img').isVisible(), true);
    await page.locator('#chatbot-toggle').click();
    assert.equal(await page.locator('#chatbot-panel').isVisible(), true);
    assert.match(await page.locator('#chatbot-panel').innerText(), /Koneksi AI belum aktif/);
    await page.locator('[data-chat-guide=partner]').click();
    assert.match(await page.locator('#chatbot-guide').innerText(), /bukan jawaban AI/);
    await page.locator('#chatbot-start').click();
    assert.equal(await page.locator('#chatbot-panel').isVisible(), false);
    await page.locator('[name=request_type]').selectOption('TCS');
    await page.locator('[name=category]').selectOption('UI/UX Design');
    await page.locator('[name=number]').fill('0100/PCT3/P/2026');
    await page.locator('[name=partner_id]').selectOption('1');
    await page.locator('[name=start]').fill('2026-10-05');
    await page.locator('[name=end]').fill('2026-11-06');
    await page.locator('#add-participant').click();
    await page.locator('.participant-name').nth(1).fill('Siswa Kedua');
    await page.locator('#preview-button').click();
    assert.match(await page.locator('#preview-content').innerText(), /Siswa Kedua/);
    assert.match(await page.locator('#preview-content').innerText(), /Thread Case Study/);
    assert.match(await page.locator('#preview-content').innerText(), /UI\/UX Design/);
    await page.locator('#close-preview').click();
    await page.locator('#save-letter').click();
    await page.locator('#history .download').waitFor();
    const downloadEvent = page.waitForEvent('download');
    await page.locator('#history .download').click();
    const download = await downloadEvent; await download.saveAs(join(dir, 'letter.pdf'));
    const pdfText = execFileSync('pdftotext', ['-layout', join(dir, 'letter.pdf'), '-'], { encoding: 'utf8' });
    assert.match(pdfText, /0100\/PCT3\/P\/2026/); assert.match(pdfText, /Siswa Browser/); assert.match(pdfText, /Siswa Kedua/); assert.match(pdfText, /Abdul Rajab/); assert.match(pdfText, /Thread Case Study/); assert.match(pdfText, /UI\/UX Design/);
    await page.locator('aside [data-view=dashboard]').click();
    mkdirSync('/workspace/artifacts', { recursive: true });
    await page.screenshot({ path: '/workspace/artifacts/eduagent-desktop.png', fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: '/workspace/artifacts/eduagent-mobile.png', fullPage: true });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'Tidak boleh ada overflow horizontal di mobile');
    await page.locator('#chatbot-toggle').click();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#chatbot-panel').isVisible(), false);
    await page.locator('aside [data-view=create]').click();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.reload(); await page.locator('#workspace').waitFor();
    assert.match(await page.locator('#recent').innerText(), /Instansi Uji Browser/);
    await page.locator('#logout').click(); await page.locator('#auth').waitFor();
    assert.equal(await page.locator('#workspace').isVisible(), false);
    assert.deepEqual(errors, []);
  } finally { await browser.close(); await new Promise(r => server.close(r)); db.close(); rmSync(dir, { recursive: true, force: true }); }
});
